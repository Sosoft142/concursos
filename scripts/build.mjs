import {readFileSync, writeFileSync, readdirSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {resolve, relative} from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const read = file => readFileSync(resolve(root, file), 'utf8');
const write = (file, text) => writeFileSync(resolve(root, file), text);
const shell = read('dist/index.html');
// GitHub Pages still serves the repository root. Keep this generated shell so
// the installed app, origin, storage and existing bookmarks keep their URL.
const rootShell = shell.replace(/(href|src)="\.\/(concursos\.css|mobile\.css|identity\.css|src\/app\.js|icon[^"/]*\.(?:png|svg))"/g, '$1="./dist/$2"');
write('index.html', rootShell);
const manifest = JSON.parse(read('dist/manifest.webmanifest'));
manifest.icons = manifest.icons.map(icon => ({...icon, src: './dist/' + icon.src.replace(/^\.\//, '')}));
write('manifest.webmanifest', JSON.stringify(manifest, null, 2) + '\n');
const files = [];
function walk(dir) {
  for (const item of readdirSync(resolve(root, dir), {withFileTypes:true})) {
    const name = `${dir}/${item.name}`;
    if (item.isDirectory()) walk(name);
    else if (/\.(?:js|css|png|svg|webmanifest)$/.test(name) && !name.endsWith('/sw.js')) files.push(name);
  }
}
walk('dist');
const version = JSON.parse(read('package.json')).version;
function worker(assets) {
  return `// Generated by scripts/build.mjs. Keep the original sw.js URL and scope.\nconst PREFIX = 'concursos:' + self.registration.scope + ':';\nconst CACHE = PREFIX + '${version}';\nconst ASSETS = ${JSON.stringify(['./','./index.html',...assets],null,2)};\nself.addEventListener('install', event => {\n  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(ASSETS)).then(() => self.skipWaiting()));\n});\nself.addEventListener('activate', event => {\n  event.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(key => (key.startsWith(PREFIX) && key !== CACHE) || key === 'organizador').map(key => caches.delete(key)))).then(() => self.clients.claim()));\n});\nself.addEventListener('fetch', event => {\n  if (event.request.method !== 'GET' || new URL(event.request.url).origin !== self.location.origin) return;\n  event.respondWith(fetch(event.request).then(response => {\n    if (response.ok && response.type !== 'opaque') {\n      const copy = response.clone();\n      event.waitUntil(caches.open(CACHE).then(cache => cache.put(event.request, copy)).catch(() => {}));\n    }\n    return response;\n  }).catch(async () => {\n    const cache = await caches.open(CACHE);\n    const saved = await cache.match(event.request);\n    if (saved) return saved;\n    if (event.request.mode === 'navigate') return (await cache.match('./index.html')) || Response.error();\n    return Response.error();\n  }));\n});\n`;
}
write('sw.js', worker(['./manifest.webmanifest', ...files.map(file=>'./'+file)]));
write('dist/sw.js', worker(files.map(file=>'./'+relative('dist',file))));
console.log(`Prepared ${version}: root compatibility shell and ${files.length} offline assets.`);
